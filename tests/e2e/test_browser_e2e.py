"""
Real Browser End-to-End Test for AI Voice Studio
Runs an authentic Google Chrome browser instance via Playwright.
Executes complete 12-step user journey, captures real screenshots,
and monitors console errors and network request failures.
"""

import asyncio
import json
import os
from pathlib import Path
import tempfile
import threading
import time
import pytest
from playwright.sync_api import sync_playwright
import uvicorn
from sqlalchemy.ext.asyncio import create_async_engine, async_sessionmaker, AsyncSession

from apps.server.src.config import settings
from apps.server.src import database
from apps.server.src.main import app
from apps.server.src.supervisor.supervisor import supervisor

CHROME_PATH = r"C:\Program Files\Google\Chrome\Application\chrome.exe"
SCREENSHOT_DIR = Path("docs/reports/screenshots").resolve()


def test_real_browser_end_to_end_journey():
    SCREENSHOT_DIR.mkdir(parents=True, exist_ok=True)
    console_errors = []
    network_failures = []

    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp_dir:
        tmp_path = Path(tmp_dir)
        settings.STUDIO_DATA_DIR = str(tmp_path)
        db_file = tmp_path / "e2e_studio.db"

        # Re-bind database engine to isolated test DB
        test_engine = create_async_engine(
            f"sqlite+aiosqlite:///{db_file}",
            connect_args={"check_same_thread": False},
        )
        database.engine = test_engine
        database.AsyncSessionLocal = async_sessionmaker(
            bind=test_engine,
            class_=AsyncSession,
            expire_on_commit=False,
        )

        # Run database migrations on fresh test DB
        from alembic.config import Config
        from alembic import command
        cfg = Config("alembic.ini")
        cfg.set_main_option("sqlalchemy.url", f"sqlite:///{db_file}")
        command.upgrade(cfg, "head")

        # Dynamically allocate free port to prevent TIME_WAIT collisions
        import socket
        import urllib.request
        def get_free_port() -> int:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                s.bind(("127.0.0.1", 0))
                return s.getsockname()[1]

        port = get_free_port()
        config = uvicorn.Config(
            app,
            host="127.0.0.1",
            port=port,
            log_level="warning",
            proxy_headers=settings.UVICORN_PROXY_HEADERS,
            forwarded_allow_ips=settings.UVICORN_FORWARDED_ALLOW_IPS,
        )
        server = uvicorn.Server(config)
        server_thread = threading.Thread(target=server.run, daemon=True)
        server_thread.start()

        # Wait until server is fully responsive
        server_ready = False
        for _ in range(40):
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/v1/auth/status", timeout=0.5) as resp:
                    if resp.status == 200:
                        server_ready = True
                        break
            except Exception:
                time.sleep(0.15)
        assert server_ready, f"Server failed to start on port {port}"

        # Read the generated one-time bootstrap token from isolated data dir
        token_file = tmp_path / ".bootstrap_token"
        assert token_file.exists(), "Bootstrap token file was not generated by server"
        token_data = json.loads(token_file.read_text(encoding="utf-8"))
        setup_token = token_data["token"]
        assert len(setup_token) == 48

        # Launch real Chrome browser via Playwright
        with sync_playwright() as p:
            browser = p.chromium.launch(
                executable_path=CHROME_PATH,
                headless=True,
            )
            context = browser.new_context(viewport={"width": 1280, "height": 900})
            page = context.new_page()

            # Listen to console and network
            page.on("console", lambda msg: console_errors.append(msg.text) if msg.type == "error" else None)
            page.on("requestfailed", lambda req: network_failures.append(f"{req.method} {req.url}: {req.failure}"))

            base_url = f"http://127.0.0.1:{port}"

            # Step 1 & 2: Open web UI
            page.goto(base_url, wait_until="networkidle")
            page.wait_for_selector("text=Khởi tạo Quản Trị Cục Bộ", timeout=10000)
            page.screenshot(path=str(SCREENSHOT_DIR / "01_onboarding_view.png"))

            # Step 3: Complete Onboarding in UI
            page.fill('input[placeholder="admin"]', "e2e_admin")
            page.fill('input[placeholder="••••••••••••"] >> nth=0', "E2EPassword123!")
            page.fill('input[placeholder="••••••••••••"] >> nth=1', "E2EPassword123!")
            page.fill('input[placeholder="Dán token 48 ký tự từ console..."]', setup_token)
            page.click('button:has-text("Hoàn tất & Khởi tạo Hệ thống")')

            # Step 4 & 5: Authenticated State & Switch to Single TTS Tab if needed
            page.wait_for_selector("text=e2e_admin", timeout=10000)
            if page.locator('button:has-text("Thử Giọng Lẻ")').count() > 0:
                page.click('button:has-text("Thử Giọng Lẻ")')
            # Wait for engine device target to be loaded and active
            page.wait_for_selector("text=CPU", timeout=10000)
            page.screenshot(path=str(SCREENSHOT_DIR / "02_speech_studio_view.png"))

            # Step 6 & 7: Select Mock Engine & Enter Vietnamese text
            mock_option = page.locator('select option[value="mock-tts"]')
            if mock_option.count() > 0:
                page.select_option('select:has(option[value="mock-tts"])', "mock-tts")
            vietnamese_text = "Hệ thống kiểm thử trình duyệt Chrome thực tế đã hoạt động ổn định và chính xác."
            page.fill('textarea[placeholder="Nhập đoạn văn bản cần chuyển thành giọng nói tại đây..."]', vietnamese_text)

            # Step 8: Click Generate Speech
            page.click('button:has-text("Tạo giọng nói")')

            # Step 9: Observe progress until completed (progress bar 100% and audio player appears)
            page.wait_for_selector("text=Tải WAV", timeout=30000)
            page.wait_for_selector("audio", state="attached", timeout=5000)
            page.screenshot(path=str(SCREENSHOT_DIR / "03_audio_generated_view.png"))

            # Step 10: Verify audio player and metadata (Supports both direct artifact URL and secure Bearer Blob)
            audio_elem = page.locator("audio")
            assert audio_elem.count() >= 1, "Audio element was not rendered"
            audio_src = audio_elem.get_attribute("src")
            assert audio_src and (audio_src.startswith("blob:") or "/api/v1/artifacts/" in audio_src), f"Audio src invalid: {audio_src}"

            # Step 11: Verify download WAV button (Supports hardened Fetch Blob button or legacy anchor)
            download_btn = page.locator('button:has-text("Tải WAV"), a:has-text("Tải WAV")')
            assert download_btn.count() >= 1
            assert download_btn.first.is_visible()

            # Step 11b: Accept any confirmation dialogs (for job cancellation)
            page.on("dialog", lambda dialog: dialog.accept())

            # Submit another job and cancel it while in flight
            page.fill('textarea[placeholder="Nhập đoạn văn bản cần chuyển thành giọng nói tại đây..."]', "Tác vụ này sẽ bị hủy kiểm thử Phase 2.")
            page.click('button:has-text("Tạo giọng nói")')

            # Wait for Cancel button and click it
            page.wait_for_selector('button:has-text("Hủy tác vụ")', timeout=5000)
            page.click('button:has-text("Hủy tác vụ")')
            page.wait_for_selector('text=CANCELLED', timeout=5000)
            page.screenshot(path=str(SCREENSHOT_DIR / "04_job_cancelled_view.png"))

            # Navigate to History Tab
            page.click('button:has-text("Lịch sử")')
            page.wait_for_selector("td:has-text('tts')", timeout=5000)
            page.wait_for_selector("text=cancelled", timeout=5000)
            page.screenshot(path=str(SCREENSHOT_DIR / "05_job_history_view.png"))

            # Step 12: Log out and confirm protected view
            page.click('button[title="Đăng xuất"]')
            page.wait_for_selector("text=Đăng Nhập Cục Bộ", timeout=5000)
            page.screenshot(path=str(SCREENSHOT_DIR / "06_logged_out_view.png"))

            browser.close()

        # Stop server and clean up resources
        server.should_exit = True
        server_thread.join(timeout=5)
        try:
            asyncio.run(supervisor.stop_all())
        except Exception:
            pass
        try:
            asyncio.run(test_engine.dispose())
        except Exception:
            pass

    # Verification: check console errors and unexpected network failures
    # Ignore favicon and expected 401 on initial unauthenticated state check
    critical_errors = [
        e for e in console_errors
        if "favicon" not in e.lower() and "401" not in e
    ]
    assert len(critical_errors) == 0, f"Unexpected browser console errors: {critical_errors}"
    critical_network_failures = [
        f for f in network_failures
        if "blob:" not in f and "favicon" not in f.lower()
    ]
    assert len(critical_network_failures) == 0, f"Unexpected failed network requests: {critical_network_failures}"

    # Confirm all 6 screenshots exist
    for num, name in [
        ("01", "01_onboarding_view.png"),
        ("02", "02_speech_studio_view.png"),
        ("03", "03_audio_generated_view.png"),
        ("04", "04_job_cancelled_view.png"),
        ("05", "05_job_history_view.png"),
        ("06", "06_logged_out_view.png"),
    ]:
        file_p = SCREENSHOT_DIR / name
        assert file_p.exists() and file_p.stat().st_size > 10000, f"Screenshot {name} is missing or empty"
